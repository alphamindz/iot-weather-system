export function renderWeatherIcon(condition: string = '', isDay = true, size = 28) {
  const c = condition.toLowerCase();
  if (c.includes('thunder') || c.includes('storm')) {
    return <CloudLightningIcon size={size} color="#f59e0b" strokeWidth={2.2} />;
  }
  if (c.includes('rain') || c.includes('drizzle') || c.includes('shower')) {
    return <CloudRainIcon size={size} color="#06b6d4" strokeWidth={2.2} />;
  }
  if (c.includes('cloud') || c.includes('overcast')) {
    return <CloudSunIcon size={size} color="#38bdf8" strokeWidth={2.2} />;
  }
  if (!isDay) {
    return <MoonIcon size={size} color="#a855f7" strokeWidth={2.2} />;
  }
  return <SunIcon size={size} color="#f59e0b" strokeWidth={2.2} />;
}
